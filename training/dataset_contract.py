"""Validated, reproducible dataset ingestion for production model training.

The training commands deliberately reject unproven local CSVs.  A dataset is
eligible only when its manifest records a public source URL, an SPDX license,
and a checksum.  This keeps a convenient demo/evaluation file from being
mistaken for a production training corpus.
"""
from __future__ import annotations

import csv
import hashlib
import json
import math
import urllib.request
from dataclasses import dataclass
from pathlib import Path
from typing import Any


class DatasetContractError(ValueError):
    """Raised when a dataset cannot be proven suitable for production use."""


ALLOWED_LICENSE_PREFIXES = (
    "CC0",
    "CC-BY",
    "CC BY",
    "MIT",
    "Apache-2.0",
    "BSD",
    "ODC",
    "PUBLIC DOMAIN",
)


@dataclass(frozen=True)
class DatasetContract:
    name: str
    source_url: str
    license: str
    sha256: str
    label_column: str
    timestamp_column: str | None = None
    group_column: str | None = None
    feature_columns: tuple[str, ...] = ()
    citation: str = ""

    @classmethod
    def from_file(cls, path: Path) -> DatasetContract:
        try:
            raw = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as exc:
            raise DatasetContractError(f"dataset manifest is unreadable: {path}") from exc
        required = ("name", "source_url", "license", "sha256", "label_column")
        missing = [key for key in required if not raw.get(key)]
        if missing:
            raise DatasetContractError(
                f"dataset manifest is incomplete; missing: {', '.join(missing)}"
            )
        license_name = str(raw["license"])
        if not any(license_name.upper().startswith(prefix.upper()) for prefix in ALLOWED_LICENSE_PREFIXES):
            raise DatasetContractError(
                f"license {license_name!r} is not on the allowed open-license list; "
                "add a legal review before training"
            )
        digest = str(raw["sha256"]).lower()
        if len(digest) != 64 or any(ch not in "0123456789abcdef" for ch in digest):
            raise DatasetContractError("manifest sha256 must be a 64-character hexadecimal digest")
        return cls(
            name=str(raw["name"]),
            source_url=str(raw["source_url"]),
            license=license_name,
            sha256=digest,
            label_column=str(raw["label_column"]),
            timestamp_column=raw.get("timestamp_column"),
            group_column=raw.get("group_column"),
            feature_columns=tuple(str(x) for x in raw.get("feature_columns", [])),
            citation=str(raw.get("citation", "")),
        )


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def obtain_dataset(dataset: Path, manifest: Path, *, download: bool = False) -> DatasetContract:
    """Load and verify a dataset described by ``manifest``.

    Downloads are opt-in and use urllib only; no traffic is generated by this
    workflow.  Existing files must still match the recorded digest.
    """
    contract = DatasetContract.from_file(manifest)
    if not dataset.exists():
        if not download:
            raise DatasetContractError(
                f"dataset {dataset} is unavailable. Download the open dataset from "
                f"{contract.source_url!r} and retry with --download, or provide --dataset."
            )
        dataset.parent.mkdir(parents=True, exist_ok=True)
        try:
            urllib.request.urlretrieve(contract.source_url, dataset)
        except (OSError, ValueError) as exc:
            raise DatasetContractError(
                f"could not download dataset from {contract.source_url!r}: {exc}"
            ) from exc
    actual = sha256_file(dataset)
    if actual != contract.sha256:
        raise DatasetContractError(
            f"dataset checksum mismatch for {dataset}: expected {contract.sha256}, got {actual}. "
            "Refusing to train on unverified data."
        )
    return contract


def read_csv_rows(dataset: Path, contract: DatasetContract) -> tuple[list[dict[str, Any]], list[str]]:
    """Read and validate finite numeric features and a binary label."""
    with dataset.open(newline="", encoding="utf-8-sig") as handle:
        reader = csv.DictReader(handle)
        columns = list(reader.fieldnames or [])
        if contract.label_column not in columns:
            raise DatasetContractError(
                f"label column {contract.label_column!r} is absent; available columns: {columns}"
            )
        if contract.timestamp_column and contract.timestamp_column not in columns:
            raise DatasetContractError(f"timestamp column {contract.timestamp_column!r} is absent")
        if contract.group_column and contract.group_column not in columns:
            raise DatasetContractError(f"group column {contract.group_column!r} is absent")
        feature_columns = list(contract.feature_columns) or [
            column
            for column in columns
            if column not in {contract.label_column, contract.timestamp_column, contract.group_column}
        ]
        if not feature_columns:
            raise DatasetContractError("manifest selects no feature columns")
        missing = [column for column in feature_columns if column not in columns]
        if missing:
            raise DatasetContractError(f"manifest feature columns are absent: {missing}")
        rows: list[dict[str, Any]] = []
        for index, raw in enumerate(reader, start=2):
            if not raw:
                continue
            try:
                label = int(float(str(raw[contract.label_column]).strip()))
            except (TypeError, ValueError) as exc:
                raise DatasetContractError(f"row {index} has a non-numeric label") from exc
            if label not in (0, 1):
                raise DatasetContractError(f"row {index} label must be binary 0/1, got {label!r}")
            row: dict[str, Any] = {"label": label, "_row": index}
            for column in feature_columns:
                try:
                    val_str = str(raw[column]).strip()
                    if val_str.lower() in ("true", "t"):
                        value = 1.0
                    elif val_str.lower() in ("false", "f"):
                        value = 0.0
                    else:
                        value = float(val_str)
                except (TypeError, ValueError) as exc:
                    raise DatasetContractError(
                        f"row {index} feature {column!r} is not numeric"
                    ) from exc
                if not math.isfinite(value):
                    raise DatasetContractError(f"row {index} feature {column!r} is not finite")
                row[column] = value
            if contract.timestamp_column:
                row["_timestamp"] = str(raw[contract.timestamp_column]).strip()
            if contract.group_column:
                row["_group"] = str(raw[contract.group_column]).strip()
            rows.append(row)
    if len(rows) < 20 or {row["label"] for row in rows} != {0, 1}:
        raise DatasetContractError("dataset must contain at least 20 rows and both binary classes")
    return rows, feature_columns


def split_rows(
    rows: list[dict[str, Any]], contract: DatasetContract, *, seed: int = 42
) -> dict[str, list[dict[str, Any]]]:
    """Create deterministic temporal or group-aware train/calibration/test splits."""
    if contract.timestamp_column:
        ordered = sorted(rows, key=lambda row: str(row.get("_timestamp", "")))
    elif contract.group_column:
        groups = sorted({str(row.get("_group", "")) for row in rows})
        # Keep groups intact and deterministic; the seed is part of provenance.
        rotation = seed % max(len(groups), 1)
        groups = groups[rotation:] + groups[:rotation]
        ordered = [row for group in groups for row in rows if str(row.get("_group", "")) == group]
    else:
        # Deterministic stratified split preserving class ratios across partitions
        import random
        rng = random.Random(seed)
        negatives = [r for r in rows if r["label"] == 0]
        positives = [r for r in rows if r["label"] == 1]
        rng.shuffle(negatives)
        rng.shuffle(positives)
        ordered = []
        n_neg, n_pos = len(negatives), len(positives)
        ratio = n_neg / max(n_pos, 1)
        neg_idx, pos_idx = 0, 0
        while neg_idx < n_neg or pos_idx < n_pos:
            target_neg = int(pos_idx * ratio)
            while neg_idx < target_neg and neg_idx < n_neg:
                ordered.append(negatives[neg_idx])
                neg_idx += 1
            if pos_idx < n_pos:
                ordered.append(positives[pos_idx])
                pos_idx += 1
        while neg_idx < n_neg:
            ordered.append(negatives[neg_idx])
            neg_idx += 1
    n = len(ordered)
    train_end = max(1, int(n * 0.60))
    calibration_end = max(train_end + 1, int(n * 0.80))
    if calibration_end >= n:
        raise DatasetContractError("dataset is too small for train/calibration/test temporal splits")
    return {
        "train": ordered[:train_end],
        "calibration": ordered[train_end:calibration_end],
        "test": ordered[calibration_end:],
    }
